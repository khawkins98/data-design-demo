/**
 * The six questions, answered on the page rather than linked from it.
 *
 * A link list was the previous shape, and it asked the reader to go and find out.
 * But the repository's own argument is that the demos do not discriminate - zero
 * requirements came back unsupported - and that the axes do. So the answers ARE
 * the landing page's content, and the demos are evidence a reader can check
 * afterwards.
 *
 * THE ANSWERS NO LONGER LIVE HERE. They moved to scripts/lib/undrr-questions.mjs so
 * that axes.html can open each axis section with the same question and the same
 * answer: a reader clicking "A6 Right-to-left" from a card below used to land on a
 * table headed `beyond native | traps | wrappers` with no mention of what they had
 * been reading. The plain-language layer existed, it was just on one page only. Both
 * pages now generate from that module and cannot drift apart.
 *
 * Prose source of truth is docs/undrr-questions.md and docs/decision-axes.md.
 */

/*
 * A stacked list, not a card grid.
 *
 * These were four-to-a-row cards, and cards were the wrong container for them. The
 * answers are two to five lines and vary in length, so an auto-filling grid set
 * every card to the tallest one's height, left the short ones padded with dead
 * space, and squeezed the text into 16rem columns - narrow enough that the answers
 * broke over four or five words a line. Reading six of those is work.
 *
 * Cards suit things you scan and pick one of, which is what the pairing cards below
 * are. These are things you READ, in order, all six. So they run full width at a
 * readable measure, one after another, with a rule between them.
 */
const questionsHtml = UNDRR_QUESTIONS.map(
  (q) => `
          <div class="question">
            <h3 class="question__title">
              ${esc(q.question)}
              <span class="question__asks">${esc(q.asks)}</span>
            </h3>
            <p class="question__answer">${esc(q.answer)}</p>
            <p class="question__axis">
              <a href="./axes.html#${esc(q.axis.toLowerCase())}"
                >Evidence: ${esc(q.axis)} ${esc(q.axisName)}</a
              >
            </p>
          </div>`,
).join("\n");

/**
 * Known-issue counts per pairing, transcribed from the TypeScript registry the
 * demo pages import. Generated by scripts/build-known-issues-json.mjs, so the
 * cards and the box on each demo page cannot disagree about what is known.
 */
const KNOWN_ISSUES_PATH = join(ROOT, "docs", "known-issues.json");
const knownIssuesDoc = existsSync(KNOWN_ISSUES_PATH)
  ? JSON.parse(readFileSync(KNOWN_ISSUES_PATH, "utf8"))
  : {};
const knownIssues = knownIssuesDoc.pairings ?? {};
/** Candidate-level totals, so a link's count matches what the link opens. */
const candidateCounts = knownIssuesDoc.candidates ?? {};

/** Reads one pairing's evidence.json, or null if the run has not produced one. */
function readEvidence(appDir) {
  const path = join(ROOT, "apps", appDir, "evidence.json");
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    process.stderr.write(`warning: ${appDir}/evidence.json is not valid JSON: ${error.message}\n`);
    return null;
  }
}

