/**
 * The views this host COULD ship, whether or not it does yet.
 *
 * Returning the applicable-but-missing ones is the point: an unbuilt realistic
 * layout then shows as a visible gap on the card instead of a silently shorter
 * list, which is the difference between "not done" and "nothing to see here".
 */
function viewsFor(appDir, hostId) {
  return VIEWS.filter((view) => view.host === null || view.host === hostId).map((view) => ({
    ...view,
    built: existsSync(join(ROOT, "apps", appDir, view.file)),
  }));
}

/*
 * Cards are built candidate-major, so each candidate's two hosts sit next to each
 * other.
 *
 * The previous order was host-major, which put all five Delta pairings in one
 * block and all five Mangrove pairings in another. Ten cards in an auto-filling
 * grid then wrapped 4/4/2, leaving a ragged final row and - worse - placing
 * `delta-mui` five cards away from `mangrove-mui`. The comparison a reader
 * actually makes is one library across the two hosts, so that is the pairing the
 * layout should put side by side.
 */
const groups = [];
for (const candidate of manifest.candidates) {
  const groupCards = [];
  for (const host of manifest.hosts) {
    const appDir = `${host.id}-${candidate.id}`;
    const evidence = readEvidence(appDir);

    let status = "not-started";
    let statusLabel = "Not started";
    if (evidence) {
      const blockers = Array.isArray(evidence.blockers) ? evidence.blockers : [];
      status = blockers.length > 0 ? "blocked" : "complete";
      statusLabel = blockers.length > 0 ? `Blocked (${blockers.length})` : "Complete";
    }

    groupCards.push({
      appDir,
      host,
      candidate,
      evidence,
      status,
      statusLabel,
      views: viewsFor(appDir, host.id),
    });
  }
  groups.push({ candidate, cards: groupCards });
}

/** Flat list, still needed for the built/total count. */
const cards = groups.flatMap((group) => group.cards);

/**
 * Renders the one card number that is a ceiling rather than a cost.
 *
 * WHAT WAS HERE BEFORE, AND WHY IT WENT. Five metrics: custom CSS lines,
 * wrappers, tokens applied, axe violations and bundle size. Every one was easy to
 * generate and at least two actively misled.
 *
 * decision-axes.md opens by arguing that volume misleads and that "a reader
 * looking for a decision will reach for whatever number is largest, which is lines
 * of code" - and then this page handed that reader ten unframed number panels in
 * which React Aria's 715 CSS lines look five times worse than Carbon's 300. The
 * A2 reading is the opposite: React Aria's rules target published state
 * attributes and it has zero hooks off the library's theming route, where Carbon
 * has 15-16. A bare "axe violations: 0" was worse still, since A7 exists to say
 * that zero automated violations is a floor and not a conformance claim.
 *
 * `tokensUnreachable` survives because it is the one figure no effort closes:
 * there is no hook to attach those tokens to. It is shown only when non-zero,
 * because "0 unreachable" is the unremarkable case and does not need a panel.
 */
function metrics(evidence) {
  const unreachable = evidence?.theming?.tokensUnreachable;
  if (!unreachable) return "";
  return `<p class="ceiling">
        <strong>${esc(unreachable)}</strong> of ${esc(
          evidence.theming?.tokensApplied
            ? unreachable + evidence.theming.tokensApplied
            : 71,
        )} UNDRR tokens unreachable
        <span class="ceiling__note">a ceiling, not a cost: there is no hook to attach them to</span>
      </p>`;
}

/**
 * Renders the worst known issue for a pairing, if there is one.
 *
 * Shown on the card rather than only inside the demo, because a reader scanning
 * ten cards to decide which to open should see that MUI cannot do RTL before they
 * spend time on it, not after.
 */
function knownIssueNote(appDir, candidateId) {
  const entry = knownIssues[appDir];
  if (!entry || !entry.headline) return "";
  const { severity, title } = entry.headline;
  const others = entry.total - 1;
  /*
   * "and 3 more" used to be inert text, so the full wording of a finding existed
   * only inside a demo page or the TypeScript registry - the most consequential
   * facts in the evaluation were the least reachable. It is now a link into the
   * register, anchored at this candidate.
   */
  /*
   * The count must match what the link opens.
   *
   * This used to read "and 3 more" from the PAIRING count while linking to the
   * register, which groups by CANDIDATE and showed 8. Both numbers were right about
   * different things, so nothing was wrong and nobody could tell - the worst kind of
   * inconsistency. It now counts what the destination counts.
   */
  const candidateTotal = candidateCounts[candidateId]?.open ?? entry.total;
  const more = ` <a class="card__issue-more" href="./issues.html#${esc(candidateId)}">${
    candidateTotal > 1 ? `all ${candidateTotal} findings` : "read it in full"
  }</a>`;
  return `<p class="card__issue card__issue--${esc(severity)}">
      <span class="card__issue-badge">${esc(
        severity === "decision" ? "Decision needed" : severity === "blocker" ? "Blocker" : "Caveat",
      )}</span>
      ${esc(title)}${more}
    </p>`;
}

/**
 * What each badge on a card actually means.
 *
 * ONE SOURCE FOR THE TOOLTIP AND THE GLOSSARY. `short` is what appears on hover or
 * focus; `long` is the glossary entry. Both are generated from here, so the pop-up
 * explanation and the glossary cannot come to disagree about what "clean" claims -
 * which they would within one revision if each were written where it is displayed.
 *
 * The badges are the most-read thing on this page and the least self-explanatory:
 * "Long labels: clean" is meaningless to anyone who has not read the brief, and a
 * glossary two screens down is not where a reader looks when a badge confuses them.
 */
