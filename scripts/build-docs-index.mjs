/**
 * The views this host COULD ship, whether or not it does yet.
 *
 * Returning the applicable-but-missing ones is the point: an unbuilt realistic
 * layout then shows as a visible gap on the card instead of a silently shorter
 * list, which is the difference between "not done" and "nothing to see here".
 */
function viewsFor(appDir, hostId) {
  return VIEWS.filter((view) => view.host === null || view.host === hostId).map((view) => ({
    ...view,
    built: existsSync(join(ROOT, "apps", appDir, view.file)),
  }));
}

/*
 * Cards are built candidate-major, so each candidate's two hosts sit next to each
 * other.
 *
 * The previous order was host-major, which put all five Delta pairings in one
 * block and all five Mangrove pairings in another. Ten cards in an auto-filling
 * grid then wrapped 4/4/2, leaving a ragged final row and - worse - placing
 * `delta-mui` five cards away from `mangrove-mui`. The comparison a reader
 * actually makes is one library across the two hosts, so that is the pairing the
 * layout should put side by side.
 */
const groups = [];
for (const candidate of manifest.candidates) {
  const groupCards = [];
  for (const host of manifest.hosts) {
    const appDir = `${host.id}-${candidate.id}`;
    const evidence = readEvidence(appDir);

    let status = "not-started";
    let statusLabel = "Not started";
    if (evidence) {
      const blockers = Array.isArray(evidence.blockers) ? evidence.blockers : [];
      status = blockers.length > 0 ? "blocked" : "complete";
      statusLabel = blockers.length > 0 ? `Blocked (${blockers.length})` : "Complete";
    }

    groupCards.push({
      appDir,
      host,
      candidate,
      evidence,
      status,
      statusLabel,
      views: viewsFor(appDir, host.id),
    });
  }
  groups.push({ candidate, cards: groupCards });
}

/** Flat list, still needed for the built/total count. */
const cards = groups.flatMap((group) => group.cards);

/** Renders the metric row shown on a completed card. */
function metrics(evidence) {
  if (!evidence) return "";

  const rows = [
    ["Custom CSS", evidence.customCss?.lines ?? null, "lines"],
    ["Wrappers", evidence.wrappers?.count ?? null, ""],
    ["Tokens applied", evidence.theming?.tokensApplied ?? null, ""],
    ["axe violations", evidence.axe?.violations ?? null, ""],
    ["Bundle", evidence.bundle?.gzippedKb ?? null, "kB gz"],
  ];

  const cells = rows
    .filter(([, value]) => value !== null && value !== undefined)
    .map(
      ([label, value, unit]) =>
        `<div class="metric"><dt>${esc(label)}</dt><dd>${esc(value)}${
          unit ? ` <span class="unit">${esc(unit)}</span>` : ""
        }</dd></div>`,
    )
    .join("");

  return cells ? `<dl class="metrics">${cells}</dl>` : "";
}

/**
 * Renders the worst known issue for a pairing, if there is one.
 *
 * Shown on the card rather than only inside the demo, because a reader scanning
 * ten cards to decide which to open should see that MUI cannot do RTL before they
 * spend time on it, not after.
 */
function knownIssueNote(appDir) {
  const entry = knownIssues[appDir];
  if (!entry || !entry.headline) return "";
  const { severity, title } = entry.headline;
  const others = entry.total - 1;
  return `<p class="card__issue card__issue--${esc(severity)}">
      <span class="card__issue-badge">${esc(
        severity === "decision" ? "Decision needed" : severity === "blocker" ? "Blocker" : "Caveat",
      )}</span>
      ${esc(title)}${others > 0 ? ` <span class="card__issue-more">and ${others} more</span>` : ""}
    </p>`;
}

/** Renders the leakage and RTL flags, which are the comparison's headline signals. */
function flags(evidence) {
  if (!evidence) return "";
  const items = [];

  if (evidence.leakage) {
    const passed = evidence.leakage.assertionPassed === true;
    items.push(
      `<li class="flag ${passed ? "flag--ok" : "flag--bad"}">Leakage: ${
        passed ? "clean" : `${evidence.leakage.differences?.length ?? 0} differences`
      }</li>`,
    );
  }
  if (evidence.rtl?.status) {
    items.push(
      `<li class="flag flag--${evidence.rtl.status === "clean" ? "ok" : "bad"}">RTL: ${esc(
        evidence.rtl.status,
      )}</li>`,
    );
  }
  if (evidence.longLabels?.status) {
    items.push(
      `<li class="flag flag--${
        evidence.longLabels.status === "clean" ? "ok" : "bad"
      }">Long labels: ${esc(evidence.longLabels.status)}</li>`,
    );
  }

  return items.length ? `<ul class="flags">${items.join("")}</ul>` : "";
}

/**
 * The per-card list of views.
 *
 * One "Open demo" link was enough when there was one page. There are now up to
 * three, and two of them are the ones that answer the Mangrove-integration
 * question - so they have to be reachable from here rather than by guessing a
 * URL.
 */
function viewLinks(card) {
  if (card.status === "not-started") {
    return `<span class="card__link card__link--disabled">Not yet built</span>`;
  }
  return `<ul class="views">${card.views
    .map((view) =>
      view.built
        ? `<li class="view"><a class="view__link" href="./${esc(card.appDir)}/${esc(
            view.href,
          )}">${esc(view.label)}</a> <span class="view__hint">${esc(view.hint)}</span></li>`
        : /*
           * An applicable view that does not exist yet is shown, greyed, rather
           * than omitted. Omitting it made an incomplete pairing look complete:
           * the reader had no way to tell a shorter list from a finished one.
           */
          `<li class="view view--missing"><span class="view__link view__link--missing">${esc(
            view.label,
          )}</span> <span class="view__hint">not built yet</span></li>`,
    )
    .join("")}</ul>`;
}

function cardMarkup(card) {
  return `
      <article class="card card--${esc(card.status)}">
        <header class="card__header">
          <h3 class="card__title">${esc(card.candidate.name)}</h3>
          <p class="card__host">on <strong>${esc(card.host.name)}</strong></p>
        </header>
        <p class="card__status" data-status="${esc(card.status)}">${esc(card.statusLabel)}</p>
        ${flags(card.evidence)}
        ${metrics(card.evidence)}
        ${viewLinks(card)}
      </article>`;
}

