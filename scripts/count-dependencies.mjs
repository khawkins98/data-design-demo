#!/usr/bin/env node
/**
 * Counts each app's PRODUCTION dependency tree by one consistent method, and
 * writes docs/dependency-counts.json.
 *
 * This exists because the per-run `bundle.dependencyCount` figures in
 * `apps/*\/evidence.json` are not comparable with each other. Ten runs recorded
 * that number by whatever method each chose, and the disagreement is not small:
 * Mantine was recorded at 112-113 where a production-only count gives 27-28, and
 * the *ordering* of the candidates changes as a result. A metric that reorders
 * the field depending on who measured it cannot be used to decide anything.
 *
 * So the recorded values are left untouched - they are each run's own evidence -
 * and this measures all ten the same way for the axis tables. The method is
 * `pnpm licenses list --prod`, which enumerates the resolved production tree and
 * gives the licence breakdown at the same time.
 *
 *   pnpm deps:count
 */

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const APPS = join(ROOT, "apps");

const apps = readdirSync(APPS, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(APPS, d.name, "package.json")))
  .map((d) => d.name)
  .sort();

const results = {};

for (const app of apps) {
  let raw;
  try {
    raw = execFileSync(
      "pnpm",
      ["--filter", `./apps/${app}`, "licenses", "list", "--prod", "--json"],
      { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    );
  } catch {
    process.stderr.write(`warning: could not enumerate dependencies for ${app}\n`);
    continue;
  }

  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    process.stderr.write(`warning: unparseable licence output for ${app}\n`);
    continue;
  }

  const packages = new Set();
  const licences = {};
  for (const [licence, entries] of Object.entries(parsed)) {
    for (const entry of entries) {
      packages.add(entry.name);
      licences[licence] = (licences[licence] ?? 0) + 1;
    }
  }

  results[app] = {
    productionPackages: packages.size,
    licences: Object.fromEntries(Object.entries(licences).sort(([a], [b]) => a.localeCompare(b))),
  };
  process.stdout.write(`${app.padEnd(22)} ${String(packages.size).padStart(4)} production packages\n`);
}

writeFileSync(
  join(ROOT, "docs", "dependency-counts.json"),
  `${JSON.stringify(
    {
      $comment:
        "GENERATED by scripts/count-dependencies.mjs (pnpm deps:count). One method for all apps, because the per-run evidence.json figures were measured inconsistently and reorder the candidates. Regenerate after changing any app's dependencies.",
      method: "pnpm licenses list --prod --json, counting distinct package names",
      apps: results,
    },
    null,
    2,
  )}\n`,
  "utf8",
);

process.stdout.write(`\nwrote docs/dependency-counts.json (${Object.keys(results).length} apps)\n`);
